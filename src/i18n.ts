/** pt-* → Brazilian Portuguese, es-* → Spanish, anything else → English */
export function strings(lang?: string): Strings {
  const l = lang?.toLowerCase() ?? '';
  if (l.startsWith('pt')) return pt;
  if (l.startsWith('es')) return es;
  return en;
}

let current: Strings = strings(typeof navigator !== 'undefined' ? navigator.language : undefined);

/** language of the HA user profile (falls back to the browser); returns true when it changed */
export function setLanguage(hass?: { language?: string; locale?: { language?: string } }): boolean {
  const next = strings(hass?.locale?.language ?? hass?.language ?? (typeof navigator !== 'undefined' ? navigator.language : undefined));
  if (next === current) return false;
  current = next;
  return true;
}

/** the strings of the current language */
export function t(): Strings {
  return current;
}
